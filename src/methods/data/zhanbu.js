/**
 * 卦名 → 上下卦与类象（用于签的「对应卦象」与断语里的象辞）。
 * 由共享的 HEX_TABLE 反查，避免再抄一遍六十四卦名。
 */
export const HEX_UP_LOW = (() => {
  const out = {}
  HEX_TABLE.forEach((row, ui) => {
    row.forEach((name, li) => {
      const up = TRIGRAMS[ui]
      const lo = TRIGRAMS[li]
      out[name] = {
        upper: up.name, lower: lo.name,
        upperXiang: up.xiang, lowerXiang: lo.xiang,
        upperWx: up.wx, lowerWx: lo.wx,
        xiang: `${up.xiang}${lo.xiang}`,
      }
    })
  })
  return out
})()

