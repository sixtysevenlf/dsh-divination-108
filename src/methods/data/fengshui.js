/**
 * 风水模块 · 私有数据表
 *
 * 只放风水类（条目 73-82）自己用的表。跨术法共用的表在 `core/tables.js`。
 *
 * ## 关于本表「吉凶分」的诚实声明
 * 下面所有数值（游年九星分、十二长生分、九星水法分、分金分……）都是**依公开通例
 * 编辑取值**（八宅大游年歌、三合十二长生水法、辅星水法八星、一百二十分金旺相孤虚
 * 空亡），不是某一秘本的原文数字。它们写在源码里、可改、可查，输出里也带
 * `fidelity` 标记。请按你自己的师承调整。
 *
 * ## 本模块采用的公开口径（写在明处）
 * 1. **玄空三元九运**：1864 年起一运，每运 20 年；运盘 = 当运星入中顺飞，
 *    轨迹 中→乾→兑→艮→离→坎→坤→震→巽（即洛书 5→6→7→8→9→1→2→3→4）。
 * 2. **山向飞星**：山星入中数 = 运盘在坐山宫之数，向星入中数 = 运盘在向首宫之数；
 *    阳顺阴逆，阴阳取**三元龙**（天元：子午卯酉阴、乾坤艮巽阳；地元：辰戌丑未阴、
 *    甲庚壬丙阳；人元：寅申巳亥阴、乙辛丁癸阳）。
 * 3. **三合**：双山五行（壬子水、癸丑金、艮寅火、甲卯木、乙辰水、巽巳金、丙午火、
 *    丁未木、坤申水、庚酉金、辛戌火、乾亥木）；以向首双山定局，坐山为入首龙，
 *    顺排十二长生。
 * 4. **一百二十分金**：甲子起于子山起点（352.5°），每格 3° 顺行六十甲子两轮，
 *    共 120 格。天干定吉凶：丙丁庚辛旺相、戊己空亡、甲乙壬癸孤虚。
 *    此排法使**每山正中恰为丙/辛旺相分金**，与「立向取旺相分金」的通说相符。
 *    （另有「透地六十龙」只排十二地支山，每山五龙支同本山，与本表不同派。）
 */

